import { applyFileEdits, type PatchCandidate } from "@/ai/verified-fix";
import { isSourceLocation } from "@complyloop/analysis-core/contract/location";
import type { Control, Project } from "@/core/project-types";
import type { Finding, Remediation } from "@complyloop/analysis-core/contract/finding-types";
import { PublicError } from "@complyloop/analysis-core/contract/public-error";
import { githubCloneUrl } from "./connect-shared";
import { createGit } from "./git";
import {
  resolveProjectGitHubToken,
  type ResolveProjectGitHubTokenOptions,
} from "./github-access";
import { parseOwnerRepo } from "./github-repo";
import { buildDeveloperHandoff } from "./handoff";
import { createOctokit, octokitErrorMessage } from "./octokit";
import { withProjectCheckout } from "./repo-checkout";

export interface PullRequestResult {
  branch: string;
  title: string;
  body: string;
  committed: boolean;
  prUrl: string | null;
  message: string;
}

async function createPullRequestViaApi(options: {
  fullName: string;
  accessToken: string;
  head: string;
  base: string;
  title: string;
  body: string;
}): Promise<string> {
  const { owner, repo } = parseOwnerRepo(options.fullName);
  const octokit = createOctokit(options.accessToken);
  try {
    const { data } = await octokit.rest.pulls.create({
      owner,
      repo,
      title: options.title,
      body: options.body,
      head: options.head,
      base: options.base,
      draft: true,
    });
    if (!data.html_url) throw new Error("GitHub PR API returned no html_url.");
    return data.html_url;
  } catch (error) {
    throw new Error(octokitErrorMessage(error, "GitHub PR API failed"));
  }
}

/**
 * Apply an already verified patch candidate on a fresh checkout, then commit,
 * push, and open a draft PR via the GitHub REST API.
 */
export async function preparePullRequest(
  project: Project,
  control: Control,
  finding: Finding,
  remediation: Remediation,
  candidate: PatchCandidate | null,
  tokenOptions?: ResolveProjectGitHubTokenOptions,
): Promise<PullRequestResult> {
  const location = finding.location;
  if (!isSourceLocation(location)) {
    throw new PublicError(
      "Runtime DOM findings cannot be committed automatically — open a manual PR from the handoff text.",
    );
  }
  if (!candidate?.complyLoop.passed || candidate.edits.length === 0) {
    throw new PublicError(
      "Generate and review a ComplyLoop-verified patch before creating a draft pull request.",
    );
  }

  return withProjectCheckout(
    project,
    async (rootPath) => {
      const git = createGit({ baseDir: rootPath });
      const inside = await git.checkIsRepo();
      if (!inside) {
        throw new PublicError(
          "Pull request preparation requires a git repository at the project root.",
        );
      }

      const shortId = finding.id.slice(0, 8);
      const branch = `complyloop/fix-${finding.checkId}-${shortId}`;
      const currentBranch = (await git.revparse(["--abbrev-ref", "HEAD"])).trim();

      const handoff = buildDeveloperHandoff(
        project,
        control,
        finding,
        remediation,
        rootPath,
      );
      const pullRequestBody = `${handoff.body}\n\n## Candidate verification\n\n- ComplyLoop: passed\n- Repository tests run in GitHub CI.`;

      try {
        const branches = await git.branchLocal();
        if (branches.all.includes(branch)) {
          await git.checkout(branch);
        } else {
          await git.checkoutLocalBranch(branch);
        }

        const changedPaths = applyFileEdits(rootPath, candidate.edits);

        await git.add(changedPaths);
        try {
          await git.commit([
            handoff.title,
            "Generated by ComplyLoop. Verify with the automated check before merge.",
          ]);
        } catch {
          // Commit may fail if the tree already matches (idempotent retry).
        }
      } catch (error) {
        try {
          await git.checkout(currentBranch);
        } catch {
          /* ignore */
        }
        throw error;
      }

      let prUrl: string | null = null;
      let message = `Branch \`${branch}\` created with the fix committed. Push and open a PR from the developer handoff.`;

      const fullName = project.github?.fullName;
      const token = await resolveProjectGitHubToken(project, tokenOptions);

      if (fullName && token) {
        const remote = githubCloneUrl(fullName, token);
        try {
          await git.push(remote, `HEAD:refs/heads/${branch}`, ["-u"]);
          const base = project.github?.defaultBranch || "main";
          prUrl = await createPullRequestViaApi({
            fullName,
            accessToken: token,
            head: branch,
            base,
            title: handoff.title,
            body: pullRequestBody,
          });
          message = `Draft pull request created via GitHub API: ${prUrl}`;
        } catch (error) {
          message =
            error instanceof Error
              ? `Branch \`${branch}\` committed locally; push/PR failed: ${error.message}`
              : `Branch \`${branch}\` committed locally; push/PR failed.`;
        }
      }

      return {
        branch,
        title: handoff.title,
        body: pullRequestBody,
        committed: true,
        prUrl,
        message,
      };
    },
    undefined,
    tokenOptions,
  );
}
