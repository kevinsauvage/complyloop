import "server-only";

import type { ReactNode } from "react";

import {
  REQUIREMENT_STATUSES,
  type RequirementStatus,
} from "@complyloop/analysis-core/contract/statuses";

import { formatDateTimeWithZone } from "@/core/datetime";
import {
  requirementStatusDisplay,
  requirementStatusReportClass,
} from "@/core/display/status";

import {
  type AuditEvidenceRow,
  type AuditRequirementRow,
  composeAuditReport,
  projectSourceLabel,
  type ReportHeaderModel,
  type ReportInput,
} from "../report-model";
import { REPORT_STYLES } from "./styles";

/**
 * Auditor-facing report as a standalone printable document. React renders it
 * (`renderToStaticMarkup`) so every piece of project-derived text is escaped by
 * construction — a report attaches compliance evidence, and a hand-written
 * escaper on that path is one forgotten call away from injecting markup.
 */
export async function buildReportHtml(
  input: ReportInput,
  scriptNonce?: string,
): Promise<string> {
  // Imported here so the module graph stays a plain Server Component graph:
  // Next rejects a static `react-dom/server` import even in a route handler.
  const { renderToStaticMarkup } = await import("react-dom/server");
  const model = composeAuditReport(input);
  return `<!DOCTYPE html>${renderToStaticMarkup(
    <ReportShell header={model.header} scriptNonce={scriptNonce}>
      <ReportSection id="summary" title="Summary">
        <SummaryGrid
          stats={[
            ["Total", model.totalRequirements],
            ["Passed", model.statusCounts.passed],
            ["Failed", model.statusCounts.failed],
            ["Pass rate", `${model.passRate}%`],
            ["Open findings", model.findingCounts.open],
          ]}
        />
        <table className="data-table">
          <thead>
            <tr>
              <th scope="col">Status</th>
              <th scope="col">Count</th>
            </tr>
          </thead>
          <tbody>
            {REQUIREMENT_STATUSES.map((status) => (
              <tr key={status}>
                <td>
                  <StatusBadge status={status} />
                </td>
                <td className="num">{model.statusCounts[status]}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </ReportSection>
      <ReportSection id="requirements" title="Requirements">
        <RequirementsTable requirements={model.requirements} />
      </ReportSection>
      <ReportSection id="evidence" title="Evidence trail">
        <EvidenceTable
          evidence={model.evidence}
          total={model.evidenceTotal}
          truncated={model.evidenceTruncated}
        />
      </ReportSection>
    </ReportShell>,
  )}`;
}

function ReportShell({
  header,
  scriptNonce,
  children,
}: {
  header: ReportHeaderModel;
  scriptNonce?: string;
  children: ReactNode;
}) {
  const title = `${header.title} — ${header.projectName}`;
  return (
    <html lang="en">
      {/* Standalone document rendered to a string for download — not a Next
          page, so `next/head` does not apply here. */}
      {/* eslint-disable-next-line @next/next/no-head-element */}
      <head>
        <meta charSet="utf-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <title>{title}</title>
        <style dangerouslySetInnerHTML={{ __html: REPORT_STYLES }} />
      </head>
      <body>
        <div className="report">
          <header className="report-header">
            <h1>{title}</h1>
            <div className="report-meta">
              <span>
                <strong>Framework:</strong> {header.frameworkName}{" "}
                {header.frameworkVersion}
              </span>
              <span>
                <strong>Source:</strong> {projectSourceLabel(header)}
              </span>
              {header.githubFullName ? (
                <span>
                  <strong>GitHub:</strong> <code>{header.githubFullName}</code>
                </span>
              ) : null}
              <span>
                <strong>Exported:</strong>{" "}
                {formatDateTimeWithZone(header.exportedAt)}
              </span>
            </div>
            <div className="no-print">
              <button type="button" id="print-report">
                Print / Save as PDF
              </button>
            </div>
          </header>
          {children}
          <footer className="report-footer">
            Generated by ComplyLoop ·{" "}
            {formatDateTimeWithZone(header.exportedAt)}
          </footer>
        </div>
        {/* The page CSP (nonce + strict-dynamic) blocks inline handlers, so the
            print button is wired by a nonce'd script, never `onclick`. */}
        <script
          nonce={scriptNonce}
          dangerouslySetInnerHTML={{
            __html:
              'document.getElementById("print-report").addEventListener("click", () => window.print());',
          }}
        />
      </body>
    </html>
  );
}

function ReportSection({
  id,
  title,
  children,
}: {
  id: string;
  title: string;
  children: ReactNode;
}) {
  return (
    <section id={id}>
      <h2>{title}</h2>
      {children}
    </section>
  );
}

function SummaryGrid({
  stats,
}: {
  stats: ReadonlyArray<readonly [string, string | number]>;
}) {
  return (
    <div className="summary-grid">
      {stats.map(([label, value]) => (
        <div className="summary-stat" key={label}>
          <div className="label">{label}</div>
          <div className="value">{value}</div>
        </div>
      ))}
    </div>
  );
}

function StatusBadge({ status }: { status: RequirementStatus }) {
  return (
    <span className={`badge ${requirementStatusReportClass(status)}`}>
      {requirementStatusDisplay(status).label}
    </span>
  );
}

function EmptyState({ message }: { message: string }) {
  return <p className="empty">{message}</p>;
}

function RequirementsTable({
  requirements,
}: {
  requirements: AuditRequirementRow[];
}) {
  if (requirements.length === 0) {
    return <EmptyState message="No requirements recorded." />;
  }

  return (
    <table className="data-table">
      <thead>
        <tr>
          <th scope="col">Control</th>
          <th scope="col">Title</th>
          <th scope="col">Status</th>
          <th scope="col">Determination</th>
          <th scope="col">Updated</th>
        </tr>
      </thead>
      <tbody>
        {requirements.map((requirement) => (
          <RequirementRow key={requirement.code} requirement={requirement} />
        ))}
      </tbody>
    </table>
  );
}

function RequirementRow({ requirement }: { requirement: AuditRequirementRow }) {
  const { exception } = requirement;
  return (
    <>
      <tr>
        <td>
          <code>{requirement.code}</code>
        </td>
        <td>{requirement.title}</td>
        <td>
          <StatusBadge status={requirement.status} />
        </td>
        <td className="muted">{requirement.determinationLabel}</td>
        <td className="nowrap muted">
          {formatDateTimeWithZone(requirement.updatedAt)}
        </td>
      </tr>
      {exception ? (
        <tr className="exception-row">
          <td colSpan={5}>
            <div className="note">
              Exception: {exception.reason} ·{" "}
              {formatDateTimeWithZone(exception.at)}
            </div>
            {exception.note ? (
              <div className="note">{exception.note}</div>
            ) : null}
          </td>
        </tr>
      ) : null}
    </>
  );
}

function EvidenceTable({
  evidence,
  total,
  truncated,
}: {
  evidence: AuditEvidenceRow[];
  total: number;
  truncated: boolean;
}) {
  if (evidence.length === 0) {
    return <EmptyState message="No evidence records." />;
  }

  return (
    <>
      {truncated ? (
        <p className="note">
          Showing the latest {evidence.length} of {total} evidence records —
          download raw JSON for the full trail.
        </p>
      ) : null}
      <table className="data-table evidence-table">
        <thead>
          <tr>
            <th scope="col">When</th>
            <th scope="col">Kind</th>
            <th scope="col">Summary</th>
          </tr>
        </thead>
        <tbody>
          {evidence.map((entry) => (
            <tr key={`${entry.at}-${entry.kindLabel}-${entry.summary}`}>
              <td className="nowrap">{formatDateTimeWithZone(entry.at)}</td>
              <td>{entry.kindLabel}</td>
              <td>{entry.summary}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </>
  );
}
