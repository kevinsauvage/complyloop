import "server-only";

import type {
  Finding,
  Remediation,
} from "@complyloop/analysis-core/contract/entities";
import { isSourceLocation } from "@complyloop/analysis-core/contract/location";
import type {
  Control,
  Project,
} from "@complyloop/analysis-core/contract/project-types";
import { PublicError } from "@complyloop/analysis-core/contract/public-error";

import { assertSingleFileEdits, type PatchCandidate } from "@/ai/verified-fix";

import { buildDeveloperHandoff } from "../assessment/handoff";
import { reportError } from "../observability";
import {
  commitFixBranch,
  createPullRequestViaApi,
  type FixBranchCommitResult,
  openPullRequestUrl,
} from "./fix-branch";
import { octokitErrorMessage } from "./github";
import { resolveProjectGitHubToken } from "./github-access";
import { effectiveBranch } from "./tracked-branch";

export interface PullRequestResult {
  branch: string;
  title: string;
  prUrl: string | null;
  /** Base branch the PR targets (the tracked branch, or its fallback). */
  base: string;
  message: string;
}

/**
 * Commits an already verified patch candidate through the GitHub Git Data API
 * and opens a draft PR. No checkout: the request handler only needs the
 * candidate's edits, and a verified single-file fix does not require a clone.
 */
export async function preparePullRequest(
  project: Project,
  control: Control,
  finding: Finding,
  remediation: Remediation,
  candidate: PatchCandidate | null,
): Promise<PullRequestResult> {
  if (!isSourceLocation(finding.location)) {
    throw new PublicError(
      "Runtime DOM and site findings cannot be committed automatically — open a manual PR from the handoff text.",
    );
  }
  if (!candidate?.complyLoop.passed || candidate.edits.length === 0) {
    throw new PublicError(
      "Generate and review a ComplyLoop-verified patch before creating a draft pull request.",
    );
  }
  // Candidates are re-hydrated from evidence; re-assert the single-file
  // invariant here so a malformed payload can never commit another path.
  assertSingleFileEdits(candidate.edits, finding.location.filePath, {
    emptyMessage: "A patch candidate must contain at least one edit.",
    offTargetMessage: (path) =>
      `Patch edits must target ${path} for this Finding.`,
  });
  const fullName = project.github?.fullName;
  const token = await resolveProjectGitHubToken(project);

  // No silent fall-through: without a repository and token nothing can be
  // committed, so claiming a "created branch" would describe work that exists
  // nowhere.
  if (!fullName || !token) {
    throw new PublicError(
      "GitHub token unavailable — reconnect the repository, then retry. Nothing was pushed.",
    );
  }

  const shortId = finding.id.slice(0, 8);
  const branch = `complyloop/fix-${finding.checkId}-${shortId}`;
  // Same base as every other project read: the tracked branch when set,
  // otherwise the repository default.
  const base = effectiveBranch(project.github) || "main";

  const handoff = buildDeveloperHandoff(project, control, finding, remediation);
  const pullRequestBody = `${handoff.body}\n\n## Candidate verification\n\n- ComplyLoop: passed\n- Repository tests run in GitHub CI.`;

  // Check the existing PR *before* committing: the commit force-resets the fix
  // branch, and a PR opened against another base would then show a diff it was
  // never built for.
  const existingBeforeCommit = await openPullRequestUrl({
    fullName,
    accessToken: token,
    head: branch,
  });
  if (existingBeforeCommit && existingBeforeCommit.base !== base) {
    throw new PublicError(
      `An open pull request for \`${branch}\` targets \`${existingBeforeCommit.base}\`, not \`${base}\`. Close it, or update the project's tracked branch, then retry.`,
    );
  }

  let committed: FixBranchCommitResult;
  try {
    committed = await commitFixBranch({
      fullName,
      accessToken: token,
      branch,
      base,
      message: `${handoff.title}\n\nGenerated by ComplyLoop. Verify with the automated check before merge.`,
      edits: candidate.edits,
    });
  } catch (error) {
    if (error instanceof PublicError) throw error;
    reportError(error, { code: "prepare_pull_request" });
    throw new PublicError(
      octokitErrorMessage(
        error,
        `Failed to commit the fix on branch \`${branch}\``,
      ),
    );
  }

  let prUrl: string;
  try {
    // The pre-commit listing is still valid unless the base fell back to the
    // repository default, which can point the reused PR at another branch.
    const existing =
      committed.base === base
        ? existingBeforeCommit
        : await openPullRequestUrl({
            fullName,
            accessToken: token,
            head: branch,
          });
    if (existing && existing.base !== committed.base) {
      throw new PublicError(
        `An open pull request for \`${branch}\` targets \`${existing.base}\`, not \`${committed.base}\`. Close it, or update the project's tracked branch, then retry.`,
      );
    }
    prUrl =
      existing?.url ??
      (await createPullRequestViaApi({
        fullName,
        accessToken: token,
        head: branch,
        base: committed.base,
        title: handoff.title,
        body: pullRequestBody,
      }));
  } catch (error) {
    if (error instanceof PublicError) throw error;
    reportError(error, { code: "prepare_pull_request" });
    throw new PublicError(
      `Branch \`${branch}\` was committed, but opening the draft pull request failed.`,
    );
  }

  return {
    branch,
    title: handoff.title,
    prUrl,
    base: committed.base,
    message: `Draft pull request created via GitHub API: ${prUrl}`,
  };
}
